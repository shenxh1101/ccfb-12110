export function formatNumber(value) {
  return new Intl.NumberFormat('zh-CN').format(Number(value) || 0);
}

export function formatPercent(value, digits = 1) {
  if (!Number.isFinite(value)) return '0%';
  return `${(value * 100).toFixed(digits)}%`;
}

export function formatTime(timestamp) {
  if (!timestamp) return '—';
  try {
    return new Date(timestamp).toLocaleString('zh-CN', { hour12: false });
  } catch {
    return '—';
  }
}

export function formatAgo(timestamp) {
  if (!timestamp) return '从未';
  const diff = Date.now() - timestamp;
  if (diff < 5000) return '刚刚';
  if (diff < 60_000) return `${Math.floor(diff / 1000)} 秒前`;
  if (diff < 3_600_000) return `${Math.floor(diff / 60_000)} 分钟前`;
  return formatTime(timestamp);
}

export function downloadBytes(filename, bytes, mime = 'application/octet-stream') {
  const blob = new Blob([bytes], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function downloadJson(filename, value) {
  downloadBytes(filename, new TextEncoder().encode(JSON.stringify(value, null, 2)), 'application/json');
}

export function readFileAsBytes(file) {
  return file.arrayBuffer().then((buffer) => new Uint8Array(buffer));
}

export function targetTypeLabel(kind) {
  return { protocol: '协议', image: '图片头', compression: '压缩' }[kind] || kind || '靶子';
}
